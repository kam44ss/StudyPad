-- ============================================================================
-- حماية إضافية اختيارية لحساب الأدمن (Multi-Factor Authentication)
-- ملاحظة مهمة: هذي الدالة الجديدة is_admin_with_mfa() ما استُخدمت بأي مكان
-- بعد - عمداً. تفعيلها بكل مكان فوراً قبل ما تتأكد MFA يشتغل لحسابك بنفسك
-- ممكن يقفلك برّا حسابك الإداري بالكامل (لأنه أول تسجيل دخول ما يكون معه
-- AAL2 لحد ما تفعّل وتتحقق من رمز TOTP). فعّلها لحسابك أول، تأكد تشتغل،
-- بعدين اطلب مني أبدّل is_admin() بـ is_admin_with_mfa() بالأماكن الحساسة.
-- ============================================================================

create or replace function is_admin_with_mfa()
returns boolean
language sql
security definer
stable
as $$
  select is_admin() and coalesce(auth.jwt() ->> 'aal', '') = 'aal2';
$$;
